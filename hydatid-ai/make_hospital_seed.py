"""Writes supabase/seed_hospitals.sql from hospitals.py (the demo directory).

Run after changing hospitals.py:   .venv/bin/python make_hospital_seed.py
Phone numbers are left empty on purpose: only the hospital can confirm its own number.
Capabilities are marked unconfirmed until a clinician checks them.
"""
import json
import os

import hospitals

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "supabase", "seed_hospitals.sql")


def lit(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def slug(name):
    return "".join(ch.lower() if ch.isalnum() else "-" for ch in name).strip("-")[:60]


def main():
    rows = []
    for h in hospitals.HOSPITALS:
        rows.append(f"  ({lit(slug(h['name']))}, {lit(h['name'])}, {lit(h['area'])}, {lit(h['type'])}, "
                    f"{h['lat']}, {h['lng']}, null, '{json.dumps(h['caps'])}'::jsonb, false)")
    sql = ("-- Generated by make_hospital_seed.py from hospitals.py. Phones are blank until confirmed.\n"
           "insert into public.hospitals (id, name, area, kind, lat, lng, phone, caps, capabilities_confirmed) values\n"
           + ",\n".join(rows) +
           "\non conflict (id) do update set name = excluded.name, area = excluded.area, kind = excluded.kind,\n"
           "  lat = excluded.lat, lng = excluded.lng, caps = excluded.caps, updated_at = now();\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(sql)
    print(f"wrote {OUT}: {len(hospitals.HOSPITALS)} hospitals")


if __name__ == "__main__":
    main()
