"""Writes supabase/seed_reference.sql from the app's own knowledge base.

Run after changing knowledge.py or rules.py:   .venv/bin/python make_reference_seed.py
The output is idempotent (upserts), so it is safe to run in the Supabase SQL Editor again.
"""
import json
import os

import knowledge

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "supabase", "seed_reference.sql")


def lit(v):
    """SQL literal for a text value (single quotes doubled)."""
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def jlit(v):
    """SQL literal for a jsonb value."""
    return lit(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def main():
    lines = ["-- Reference data generated by make_reference_seed.py (do not hand-edit)", ""]

    info = knowledge.stage_info()
    lines.append("insert into public.stage_reference (stage, name, phase, plain, means, rule, signs, key_clues, triggers, sort_order) values")
    rows = []
    for i, (stage, s) in enumerate(info.items()):
        rows.append(f"  ({lit(stage)}, {lit(s.get('name'))}, {lit(s.get('phase'))}, {lit(s.get('plain'))}, {lit(s.get('means'))}, "
                    f"{lit(s.get('rule'))}, {jlit(s.get('signs', []))}, {jlit(s.get('key_clues', []))}, {jlit(s.get('triggers', []))}, {i})")
    lines.append(",\n".join(rows))
    lines.append("on conflict (stage) do update set name = excluded.name, phase = excluded.phase, plain = excluded.plain, "
                 "means = excluded.means, rule = excluded.rule, signs = excluded.signs, key_clues = excluded.key_clues, "
                 "triggers = excluded.triggers, sort_order = excluded.sort_order;")
    lines.append("")

    g = knowledge.graph()
    lines.append("insert into public.kg_nodes (id, label, grp, info) values")
    lines.append(",\n".join(f"  ({lit(n['id'])}, {lit(n['label'])}, {lit(n['group'])}, {lit(n.get('info', ''))})" for n in g["nodes"]))
    lines.append("on conflict (id) do update set label = excluded.label, grp = excluded.grp, info = excluded.info;")
    lines.append("")

    lines.append("delete from public.kg_edges;")
    lines.append("insert into public.kg_edges (source, target, kind) values")
    lines.append(",\n".join(f"  ({lit(l['source'])}, {lit(l['target'])}, {lit(l['kind'])})" for l in g["links"]) + ";")
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(info)} stages, {len(g['nodes'])} graph nodes, {len(g['links'])} graph links")


if __name__ == "__main__":
    main()
